-- Исходящая очередь доменных событий. Строки пишутся в одной транзакции
-- с задачей: только так «задача изменилась» и «об изменении рассказали»
-- становятся одним фактом, а не двумя, из которых второй может не случиться.
CREATE TABLE outbox (
    -- Порядковый номер, он же порядок доставки: события описывают прошлое,
    -- и рассказывать о нём надо в том порядке, в каком оно происходило.
    id           bigserial   PRIMARY KEY,

    -- Задача, с которой всё случилось. Внешнего ключа на tasks нет намеренно:
    -- очередь переживает свой агрегат — событие об удалении должно уехать
    -- и тогда, когда удалять уже нечего.
    aggregate_id text        NOT NULL,

    -- Имя события из констант домена. Как и у статуса, CHECK на значения нет:
    -- список имён живёт в домене и второго носителя заводить нельзя.
    name         text        NOT NULL,

    -- Поля события. jsonb, а не text: по нему можно искать и его проверяет
    -- сама база — испорченный JSON не доедет до потребителя молча.
    payload      jsonb       NOT NULL,

    occurred_at  timestamptz NOT NULL,

    -- Отметка доставки. NULL означает «ещё в очереди», и по нему же построен
    -- частичный индекс ниже.
    published_at timestamptz,

    -- Счётчик попыток и последняя ошибка — не для решения, а для человека,
    -- который придёт разбираться, почему очередь не пустеет.
    attempts     integer     NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    last_error   text
);

-- Индекс частичный: доставщика интересует только неотправленное, а строк
-- отправленных со временем становится подавляюще больше. Полный индекс рос бы
-- вместе с историей и не давал бы ничего сверх этого.
CREATE INDEX outbox_pending_idx ON outbox (id) WHERE published_at IS NULL;

