-- Ключи идемпотентности: чем клиент говорит «это тот же самый запрос,
-- а не новый». Записываются в одной транзакции с задачей — иначе повтор,
-- пришедший между записью задачи и записью ключа, создал бы дубль, ради
-- защиты от которого всё и затевалось.
CREATE TABLE idempotency_keys (
    -- Ключ скоупится владельцем: он приходит от клиента, и без владельца
    -- чужой ключ возвращал бы чужую задачу.
    owner_id    text        NOT NULL,
    key         text        NOT NULL,

    -- Отпечаток запроса. Тот же ключ с другим содержимым — не повтор, а
    -- ошибка клиента, и молча отдавать ему прошлый ответ нельзя: он спросил
    -- о другом.
    fingerprint bytea       NOT NULL,

    -- Ответ, который возвращается на повтор. Пока это только идентификатор
    -- задачи: тело ответа на создание из него и собирается.
    task_id     text        NOT NULL CHECK (char_length(task_id) = 32),

    created_at  timestamptz NOT NULL,

    -- Первичный ключ он же замок: параллельный повтор ждёт на нём, пока
    -- первый запрос не зафиксируется, и после этого видит готовый ответ.
    PRIMARY KEY (owner_id, key)
);

-- Индекса по created_at нет: убирать старые ключи пока нечем и незачем —
-- уборка приедет вместе с планировщиком, своей миграцией и вместе с тем
-- запросом, ради которого нужна.

-- +goose Down

DROP TABLE idempotency_keys;
