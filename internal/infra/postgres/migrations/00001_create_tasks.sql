-- Таблица задач. Одна строка — один агрегат целиком: транзакционная граница
-- домена проходит по задаче, и разносить её поля по нескольким таблицам
-- значило бы сочинить границу, которой в домене нет.
CREATE TABLE tasks (
    -- Идентификатор хранится текстом, а не типом uuid. TaskID — это 32
    -- шестнадцатеричные цифры без дефисов, и uuid вернул бы их с дефисами,
    -- то есть в форме, которую ParseTaskID не примет. Приводить туда-обратно
    -- значило бы поселить в идентичности домена заботу хранилища.
    id           text        PRIMARY KEY CHECK (char_length(id) = 32),

    owner_id     text        NOT NULL,
    title        text        NOT NULL,
    description  text        NOT NULL,

    -- Статус и приоритет — текст без CHECK на значения. Список статусов живёт
    -- в statusNames, приоритетов — в priorityNames, и у каждого правила ровно
    -- один носитель. CHECK здесь стал бы вторым и разошёлся бы с первым молча:
    -- новый статус добавили бы одной строкой в домене, а база отвергала бы его
    -- при записи. Неизвестное значение ловит ParseStatus на подъёме.
    status       text        NOT NULL,
    priority     text        NOT NULL,

    -- Необязательные поля: NULL означает «срока нет» и «не выполнена», а не
    -- «поле не заполнили».
    due_date     timestamptz,
    completed_at timestamptz,

    created_at   timestamptz NOT NULL,
    updated_at   timestamptz NOT NULL,

    -- Версия ведётся агрегатом и служит основой оптимистичной блокировки:
    -- обновление сверяется с ней в WHERE. У живой задачи она всегда не меньше
    -- единицы — ноль означал бы «в хранилище не бывала».
    version      integer     NOT NULL CHECK (version > 0)
);

-- Индекса по владельцу нет намеренно: сейчас по нему никто не ищет. Он
-- приедет вместе со списками и фильтрами — своей миграцией и вместе с теми
-- запросами, ради которых нужен.

-- +goose Down

DROP TABLE tasks;
