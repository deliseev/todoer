package postgres

import "errors"

// Ошибки, которые пакет порождает сам. Тексты английские, в нижнем регистре
// и без точки: их читают логи и поиск по трекеру.
var (
	// errNilTask — вместо задачи в Save передали nil.
	//
	// Хранилище стоит на границе и мусор с той стороны обязано пережить:
	// забытая наверху проверка ошибки не повод ронять процесс целиком.
	errNilTask = errors.New("postgres: task is nil")

	// errCorruptRow — строка в базе не разбирается в доменные значения.
	//
	// Классификация своя, а не доменная ошибка как есть, и это не украшение:
	// по ErrUnknownStatus, ErrInvalidTaskID, ErrEmptyTitle и прочим фабричным
	// сентинелям транспорт отвечает 400 — они заведены для негодного ввода
	// клиента. Здесь испорчен не запрос, а строка в базе: запрос был законным,
	// починить его клиент не может, и правильный ответ ему — 500. Поэтому
	// доменная ошибка уезжает подробностью, а не причиной: попади она в
	// цепочку, errors.Is у транспорта опознал бы её и обвинил в порче данных
	// того, кто просто прочитал задачу.
	errCorruptRow = errors.New("postgres: stored task is unreadable")

	// ErrSchemaOutdated — схема в базе старше той, на которую рассчитан код.
	//
	// Ошибка экспортируется: с ней сверяется композиционный корень, чтобы
	// отличить «накатите миграции» от любого другого отказа при старте.
	ErrSchemaOutdated = errors.New("postgres: database schema is outdated")
)
