// Package outbox доставляет доменные события из исходящей очереди.
//
// Очередь наполняет слой сценариев — в одной транзакции с задачей, — а этот
// пакет её разгребает. Отделён от хранилища намеренно: политика доставки не
// имеет отношения к SQL, и наоборот. Postgres реализует здешние порты Queue
// и Waiter, а сам доставщик о базе ничего не знает и проверяется без неё.
//
// Доставка — at-least-once. Между отправкой и отметкой лежит окно, в котором
// падение процесса означает повторную отправку того же сообщения, и закрыть
// его нечем: подтверждения от получателя и отметки в базе — две разные записи
// в двух разных местах. Поэтому дедупликация — обязанность получателя, и это
// не недоделка, а условие задачи.
package outbox

import (
	"context"
	"time"
)

// Message — событие в том виде, в каком оно лежит в очереди.
//
// Доменных типов здесь нет, и это не упрощение: события конструирует только
// агрегат, восстановить их из строки нечем и незачем. Доставщику нужны имя,
// адресат и полезная нагрузка — тем он и обходится.
type Message struct {
	// ID — порядковый номер в очереди, он же порядок доставки.
	ID int64
	// AggregateID — задача, с которой всё случилось.
	AggregateID string
	// Name — имя доменного события.
	Name string
	// Payload — поля события, свёрнутые в JSON.
	Payload []byte
	// OccurredAt — момент, когда факт произошёл.
	OccurredAt time.Time
}

// Queue — порт очереди со стороны доставщика.
type Queue interface {
	// Take забирает из очереди до limit сообщений в порядке очереди,
	// придерживая их от других доставщиков, и передаёт их deliver.
	//
	// Порядок очереди — среди равно пробованных: партия набирается из тех,
	// кому доставка не удавалась реже всего. Иначе сообщение, которое
	// получатель не принимает, держало бы всё, что встало за ним, — партия
	// уезжает целиком или никак. Пропущенное не потеряно: оставшись без
	// сообщений посвежее, очередь возвращается к нему.
	//
	// Успех deliver отмечается в очереди той же операцией, что и изъятие:
	// разъедься эти два действия — сообщение уехало бы дважды или не уехало
	// бы вовсе. Отказ deliver сообщения в очереди оставляет, но запоминает
	// попытку и её причину: очередь, которая не пустеет, обязана уметь
	// объяснить почему.
	//
	// Возвращает число взятых сообщений. Ноль означает пустую очередь;
	// deliver в этом случае не вызывается — будить получателя впустую незачем.
	Take(ctx context.Context, limit int, deliver func(ctx context.Context, messages []Message) error) (int, error)
}

// Publisher — порт доставки сообщений наружу.
//
// Объявлен здесь, у потребителя: во что именно уезжают события — шина,
// журнал или ничто — доставщика не касается, ему довольно ответа «взяли».
type Publisher interface {
	// Publish отправляет сообщения в порядке очереди.
	Publish(ctx context.Context, messages []Message) error
}

// Waiter — порт ожидания побудки.
type Waiter interface {
	// Wait ждёт сигнала о пополнении очереди, но не дольше timeout.
	//
	// Истёкший срок — не ошибка: это страховочный опрос. Сигнал ненадёжен по
	// своей природе — случившийся, пока никто не слушал, не повторится, —
	// и без опроса «не потерять» держалось бы на нём одном.
	Wait(ctx context.Context, timeout time.Duration) error
}

// NopPublisher — реализация Publisher, молча принимающая сообщения.
//
// Шины событий ещё нет, и это честная заглушка на её месте: сообщения
// остаются в таблице с отметкой о доставке, так что теряется не событие,
// а только его путешествие наружу. Когда шина появится, поменяется ровно
// эта реализация.
type NopPublisher struct{}

// Publish принимает сообщения и ничего с ними не делает.
func (NopPublisher) Publish(context.Context, []Message) error {
	return nil
}
