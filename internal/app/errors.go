// Package app содержит сценарии использования поверх доменной модели.
//
// Слой отвечает за оркестровку, а не за правила: разбирает внешний ввод в
// значимые объекты домена, поднимает агрегат из хранилища, проверяет права
// на него, вызывает один доменный метод и фиксирует результат. Ни одно
// доменное правило здесь не дублируется и не перепроверяется.
package app

import "errors"

// Сентинельные ошибки слоя сценариев. Вызывающая сторона сверяет их через
// errors.Is, поэтому обёртки обязаны использовать %w.
var (
	// ErrTaskNotFound — задачи с таким идентификатором в хранилище нет.
	ErrTaskNotFound = errors.New("app: task not found")
	// ErrVersionConflict — задачу изменили параллельно, версия устарела.
	ErrVersionConflict = errors.New("app: task version conflict")
	// ErrForbidden — задача принадлежит другому владельцу.
	//
	// Домен об этом правиле не знает намеренно: Task хранит OwnerID как
	// идентичность и ни с чем его не сравнивает. Сопоставить владельца
	// задачи с тем, кто её меняет, — работа сценария.
	ErrForbidden = errors.New("app: task belongs to another owner")

	// ErrMissingDependency — сервис собран без обязательной зависимости.
	ErrMissingDependency = errors.New("app: missing dependency")
)
