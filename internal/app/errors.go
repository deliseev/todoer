// Package app содержит сценарии использования поверх доменной модели.
//
// Слой отвечает за оркестровку, а не за правила: разбирает внешний ввод в
// значимые объекты домена, поднимает агрегат из хранилища, проверяет права
// на него, вызывает один доменный метод и фиксирует результат. Ни одно
// доменное правило здесь не дублируется и не перепроверяется.
package app

import "errors"

// Сентинельные ошибки слоя сценариев. Вызывающая сторона сверяет их через
// errors.Is, поэтому обёртки обязаны использовать %w.
var (
	// ErrTaskNotFound — задачи с таким идентификатором у этого владельца нет.
	//
	// Тем же самым отвечает и попытка тронуть чужую задачу: отдельной ошибки
	// «нельзя» не существует намеренно, иначе она сообщала бы постороннему,
	// что такая задача вообще есть. Домен об этом правиле не знает: Task
	// хранит OwnerID как идентичность и ни с чем его не сравнивает,
	// сопоставление владельцев — работа сценария.
	ErrTaskNotFound = errors.New("app: task not found")
	// ErrVersionConflict — задачу изменили параллельно, версия устарела.
	ErrVersionConflict = errors.New("app: task version conflict")

	// ErrIdempotencyKeyReused — тот же ключ идемпотентности прислан с другим
	// запросом.
	//
	// Это не повтор, а ошибка клиента: он спросил о другом, и отдавать ему
	// ответ на прошлый вопрос нельзя — иначе он решит, что создал одно,
	// а создано будет другое. Транспорт отвечает на это конфликтом.
	ErrIdempotencyKeyReused = errors.New("app: idempotency key reused with a different request")

	// ErrIdempotencyKeyTooLong — ключ идемпотентности длиннее
	// MaxIdempotencyKeyLength байт.
	//
	// Ключ приходит от клиента и ложится в хранилище под замок, которым
	// повторы и разводятся; замок этот не резиновый, и без потолка непомерный
	// ключ доходил бы до записи и возвращался отказом хранилища — 500 за то,
	// что испортил клиент. Транспорт отвечает на это негодным запросом.
	ErrIdempotencyKeyTooLong = errors.New("app: idempotency key is too long")

	// ErrEmptyUpdate — команда частичного изменения не несёт ни одного поля.
	//
	// Молча отвечать успехом на такой запрос нельзя: он ничего не изменил,
	// а вызывающий уверен в обратном.
	ErrEmptyUpdate = errors.New("app: update command has no fields")

	// ErrMissingDependency — сервис собран без обязательной зависимости.
	ErrMissingDependency = errors.New("app: missing dependency")
)
