package app

import (
	"context"
	"time"

	"github.com/deliseev/todoer/internal/domain/todo"
)

// Clock — порт получения текущего времени.
//
// Домен часов не знает: каждый его мутирующий метод принимает момент
// параметром. Спрашивает время ровно один слой — этот, поэтому и порт
// объявлен здесь, у своего единственного потребителя. Реализация живёт
// в инфраструктуре, тесты подставляют свою.
type Clock interface {
	Now() time.Time
}

// Repository — порт хранилища агрегата Task.
//
// Реализации живут в инфраструктуре и не имеют права знать о сценариях.
// Границу агрегата порт не нарушает: наружу выдаётся и внутрь принимается
// целая задача, а не её отдельные поля.
//
// Обе операции обязаны уважать отмену контекста и возвращать ошибку,
// из которой errors.Is достанет context.Canceled или
// context.DeadlineExceeded. Сценарий контекст сам не проверяет: отмена
// посреди работы всё равно ловится только тем, кто в этот момент работает.
//
// Версия, на которой задачу подняли, живёт на этой границе, а не в агрегате:
// «откуда взялся этот объект в памяти» — вопрос хранилища, и домену его
// задавать незачем. Get отдаёт версию вместе с задачей, Save принимает её
// обратно; сценарий это число не вычисляет, а переносит.
type Repository interface {
	// Get поднимает задачу из хранилища и сообщает версию, которой она
	// оттуда пришла. Для отсутствующей задачи возвращает ошибку,
	// обёрнутую ErrTaskNotFound.
	//
	// Пара (nil, nil) запрещена: сценарий проверяет ошибку и сразу работает
	// с задачей, поэтому при nil-ошибке задача обязана быть.
	Get(ctx context.Context, id todo.TaskID) (task *todo.Task, loadedVersion int, err error)

	// Save сохраняет задачу, соблюдая оптимистичную блокировку.
	//
	// Сверяться нужно с loadedVersion — тем, что вернул Get, — а не с текущей
	// версией задачи: между Get и Save мутаций может быть сколько угодно,
	// и «создать, начать, записать один раз» — законный сценарий, для
	// обновления не меньше, чем для вставки. Выводить ожидаемую версию из
	// сохраняемой нельзя: писатель, накопивший две мутации, так затирает
	// чужую запись, сделанную между его Get и Save.
	//
	// Запись принимается, когда сохранённая версия равна loadedVersion,
	// а для новой задачи (loadedVersion == 0) — когда записи ещё нет.
	// Всё прочее — ErrVersionConflict.
	//
	// Nil вместо задачи — нарушение контракта; реализация обязана вернуть
	// ошибку, а не паниковать.
	Save(ctx context.Context, task *todo.Task, loadedVersion int) error
}

// UnitOfWork — порт единицы работы: всё, что сделано внутри, фиксируется
// вместе или не фиксируется вовсе.
//
// Слово «транзакция» здесь не звучит намеренно: сценарию нужна атомарность,
// а чем она достигнута — транзакцией базы, блокировкой карты в памяти или
// чем-то третьим — вопрос реализации. Порт обещает только неделимость.
//
// Ради неё он и заведён: задача и её события обязаны оказаться в хранилище
// одним движением. Записанная задача, о которой не осталось события, — это
// изменение, о котором никто никогда не узнает; событие без задачи — рассказ
// о том, чего не было.
type UnitOfWork interface {
	// Do выполняет работу и фиксирует её результат.
	//
	// Ошибка работы отменяет всё, что та успела сделать, и возвращается
	// вызывающему нетронутой: по ней он и ветвится. Паника внутри работы
	// тоже обязана откатить начатое — незавершённая работа не становится
	// завершённой оттого, что вышла необычным путём.
	Do(ctx context.Context, work func(ctx context.Context, tx Tx) error) error
}

// Tx — доступ к хранилищам внутри одной единицы работы.
//
// Отдельным типом, а не парой аргументов колбэка: список того, что пишется
// вместе, будет расти, и добавление к нему не должно переписывать все вызовы.
type Tx interface {
	// Tasks отдаёт хранилище задач, работающее внутри этой единицы работы.
	Tasks() Repository
	// Outbox отдаёт исходящую очередь событий этой же единицы работы.
	Outbox() Outbox
	// Keys отдаёт хранилище ключей идемпотентности этой же единицы работы.
	Keys() IdempotencyStore
}

// IdempotencyKey — ключ вместе с тем, что за ним стоит.
//
// Владелец — часть ключа, а не приложение к нему: ключ придумывает клиент,
// и без владельца чужой ключ возвращал бы постороннему чужую задачу.
type IdempotencyKey struct {
	// OwnerID — владелец, от имени которого пришёл запрос.
	OwnerID todo.OwnerID
	// Key — то, что прислал клиент.
	Key string
	// Fingerprint — отпечаток запроса: тот же ключ с другим содержимым
	// повтором не считается.
	Fingerprint []byte
	// TaskID — задача, которую создаёт этот запрос.
	TaskID todo.TaskID
}

// TaskQueries — порт стороны чтения: списки и отборы.
//
// Отдельный порт, а не расширение Repository, и это не косметика: чтения не
// поднимают агрегат, не двигают версию, не порождают событий и не нуждаются
// в блокировке. Repository работает с одной задачей и отдаёт агрегат, здесь
// же наружу уезжает плоское представление — то, что читают, а не то, что
// изменяют.
type TaskQueries interface {
	// List возвращает не больше filter.Limit задач в порядке, заданном
	// фильтром: сначала по выбранному полю, затем по идентификатору —
	// он разрешает ничьи, без чего у страницы не было бы однозначной точки
	// продолжения.
	//
	// Про «сегодня», размер страницы по умолчанию и устройство курсора
	// реализация не знает: всё это посчитано до неё.
	List(ctx context.Context, filter TaskFilter) ([]TaskView, error)
}

// IdempotencyStore — порт хранилища ключей идемпотентности.
//
// Живёт внутри единицы работы, и это всё, ради чего он такой: ключ обязан
// записаться той же операцией, что и задача. Разъедься они — повтор,
// пришедший между двумя записями, создал бы дубль, ради защиты от которого
// ключ и придуман.
type IdempotencyStore interface {
	// Reserve закрепляет ключ за задачей и сообщает, чем дело кончилось.
	//
	// Свободный ключ достаётся вызывающему: возвращается его же задача и
	// replayed = false. Занятый тем же запросом — повтор: возвращается
	// задача, записанная первым запросом, и replayed = true, а вызывающему
	// остаётся ничего не создавать.
	//
	// Занятый ключ с другим отпечатком — ErrIdempotencyKeyReused: клиент
	// спросил о другом, и отдавать ему прошлый ответ нельзя.
	//
	// Одновременные повторы одного ключа обязаны разойтись так же:
	// закрепить его вправе ровно один, остальные получают повтор.
	Reserve(ctx context.Context, key IdempotencyKey) (taskID todo.TaskID, replayed bool, err error)
}

// Outbox — порт исходящей очереди доменных событий.
//
// Сценарий кладёт события рядом с задачей и на этом свою роль заканчивает:
// доставка — работа отдельного механизма, который читает очередь. Порта
// чтения здесь нет намеренно, потому что читает не сценарий.
type Outbox interface {
	// Add кладёт события в очередь в порядке их возникновения.
	// Пустая партия — корректный вход и в очередь ничего не добавляет.
	Add(ctx context.Context, events []todo.DomainEvent) error
}
