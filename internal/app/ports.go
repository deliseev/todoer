package app

import (
	"context"
	"time"

	"github.com/deliseev/todoer/internal/domain/todo"
)

// Clock — порт получения текущего времени.
//
// Домен часов не знает: каждый его мутирующий метод принимает момент
// параметром. Спрашивает время ровно один слой — этот, поэтому и порт
// объявлен здесь, у своего единственного потребителя. Реализация живёт
// в инфраструктуре, тесты подставляют свою.
type Clock interface {
	Now() time.Time
}

// Repository — порт хранилища агрегата Task.
//
// Реализации живут в инфраструктуре и не имеют права знать о сценариях.
// Границу агрегата порт не нарушает: наружу выдаётся и внутрь принимается
// целая задача, а не её отдельные поля.
//
// Обе операции обязаны уважать отмену контекста и возвращать ошибку,
// из которой errors.Is достанет context.Canceled или
// context.DeadlineExceeded. Сценарий контекст сам не проверяет: отмена
// посреди работы всё равно ловится только тем, кто в этот момент работает.
type Repository interface {
	// Get поднимает задачу из хранилища.
	// Для отсутствующей задачи возвращает ошибку, обёрнутую ErrTaskNotFound.
	Get(ctx context.Context, id todo.TaskID) (*todo.Task, error)

	// Save сохраняет задачу, соблюдая оптимистичную блокировку по версии.
	//
	// Версию агрегат ведёт сам: каждая успешная мутация делает Version()
	// строго больше, чем было в момент подъёма. Поэтому запись принимается
	// только тогда, когда сохранённая версия меньше версии сохраняемой
	// задачи. Иначе кто-то успел записать раньше и Save возвращает ошибку,
	// обёрнутую ErrVersionConflict.
	Save(ctx context.Context, task *todo.Task) error
}

// EventPublisher — порт доставки доменных событий за пределы сценария.
//
// В отличие от Repository, сюда приходит контекст, лишённый отмены: к моменту
// публикации задача уже записана, и отмена запроса не повод молчать о том,
// что произошло. Поэтому срок на доставку и политику повторов реализация
// назначает себе сама — снаружи их взять неоткуда.
type EventPublisher interface {
	// Publish отправляет события в порядке их возникновения.
	// Пустой срез — корректный вход и не должен считаться ошибкой.
	Publish(ctx context.Context, events []todo.DomainEvent) error
}

// NopPublisher — публикатор, который молча отбрасывает события.
// Нужен там, где доставка ещё не подключена, чтобы сервис не собирали с nil.
type NopPublisher struct{}

// Publish ничего не делает и всегда возвращает nil.
func (NopPublisher) Publish(context.Context, []todo.DomainEvent) error {
	return nil
}
